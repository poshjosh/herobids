/**
 * Derive a style tier from the agent's technical config.
 * Falls back to 'standard' when not determinable.
 */
export function deriveStyleTier(technicalConfig: TechnicalConfig): 'economy' | 'standard' | 'premium' {
  const preset = (technicalConfig as Record<string, unknown>)['preset'];
  if (typeof preset === 'string') {
    if (preset.includes('economy')) return 'economy';
    if (preset.includes('premium')) return 'premium';
  }
  return 'standard';
}

/**
 * Derive a venue family from the agent's technical config.
 * Falls back to 'unknown' when not determinable.
 */
export function deriveVenueFamily(technicalConfig: TechnicalConfig): string {
  const venue = (technicalConfig as Record<string, unknown>)['venue'];
  if (typeof venue === 'string') return venue;
  return 'unknown';
}

