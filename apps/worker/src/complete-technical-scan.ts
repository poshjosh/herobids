/**
 * Build persistable candidates from the scan phase result.
 *
 * Entry-candidate signals and exit advisories are recorded. Candidates that
 * were discovered but did not produce signals are recorded as `scored_no_signal`
 * to enable peer-preset comparison in the review pre-check.
 */
export function buildPersistableCandidates(
  agentId: string,
  scannedAt: string,
  phaseResult: TechnicalPhaseResult,
  technicalConfig: TechnicalConfig,
): PersistableScanCandidate[] {
  const venueFamily = deriveVenueFamily(technicalConfig);
  const styleTier = deriveStyleTier(technicalConfig);
  const scanScope = `${venueFamily}_${styleTier}`;
  // Use a scan version derived from the configured indicators — this is an
  // approximate behavior version until Plan 012 delivers the authoritative one.
  const scanVersion = `ts-${styleTier}-v1`;
  const presetKey = (technicalConfig as Record<string, unknown>)['preset'] as string ?? 'unknown';
  const behaviorVersion = scanVersion;

  const candidates: PersistableScanCandidate[] = [];
  const seen = new Set<string>();

  // Entry signals
  for (let i = 0; i < phaseResult.signals.length; i++) {
    const signal = phaseResult.signals[i];
    if (!signal) continue;
    const id = crypto.randomUUID();
    const rawId = signal.instrumentId || signal.symbol;

    // Phase 4: DEX signals carry exact on-chain identity for execution and pricing.
    // Orderbook signals remain unchanged (instrumentKind: 'orderbook').
    const isSwap = signal.venueType === 'swap';
    const instrumentKind: PersistableScanCandidate['instrumentKind'] = isSwap ? 'dex' : 'orderbook';
    const network = isSwap ? signal.swapExecutionIdentity?.network : undefined;
    const address = isSwap ? signal.swapExecutionIdentity?.baseAddress : undefined;

    candidates.push({
      id,
      agentId,
      scannedAt,
      scanVersion,
      activePresetKey: presetKey,
      presetBehaviorVersion: behaviorVersion,
      instrumentKind,
      venueFamily,
      styleTier,
      symbol: signal.symbol,
      network,
      address,
      rawCandidateId: rawId,
      resolutionStatus: signal.symbol ? 'resolved' : 'unresolved',
      candidateRank: i + 1,
      scanScope,
      signalFacts: {
        signalType: 'entry_candidate',
        indication: signal.intent === 'go_long' ? 'bullish' : 'bearish',
        strength: signal.confidence,
        primaryIndicator: Object.entries(signal.indicators)
          .filter(([, v]) => v !== undefined)
          .map(([k]) => k)[0] ?? 'unknown',
        indicators: signal.indicators,
      },
      confidence: signal.confidence,
      regimeBucket: phaseResult.regimeResult?.pass ? 'favorable' : phaseResult.regimeResult?.pass === false ? 'blocked' : 'unavailable',
      volatilityFact: undefined,
      dataFreshnessTs: scannedAt,
      disposition: 'entry_candidate',
    });
    seen.add(rawId);
  }

  // Exit advisories from position indicators
  for (let i = 0; i < phaseResult.positionIndicators.length; i++) {
    const ind = phaseResult.positionIndicators[i];
    if (!ind || !ind.exitAdvisory) continue;
    const rawId = ind.instrumentId ?? ind.symbol;
    if (seen.has(rawId)) continue;

    const rank = candidates.length + 1;
    candidates.push({
      id: crypto.randomUUID(),
      agentId,
      scannedAt,
      scanVersion,
      activePresetKey: presetKey,
      presetBehaviorVersion: behaviorVersion,
      instrumentKind: 'orderbook',
      venueFamily,
      styleTier,
      symbol: ind.symbol,
      rawCandidateId: rawId,
      resolutionStatus: ind.symbol ? 'resolved' : 'unresolved',
      candidateRank: rank,
      scanScope,
      signalFacts: {
        signalType: 'exit_advisory',
        indication: ind.side === 'long' ? 'bearish' : 'bullish',
        rsi: ind.rsi,
      },
      confidence: undefined,
      regimeBucket: phaseResult.regimeResult?.pass ? 'favorable' : phaseResult.regimeResult?.pass === false ? 'blocked' : 'unavailable',
      volatilityFact: undefined,
      dataFreshnessTs: scannedAt,
      disposition: 'exit_advisory',
    });
    seen.add(rawId);
  }

  return candidates;
}

// ── Scan metrics persistence helper ────────────────────────────────────────

/**
 * Build a {@link ScanMetricInput} from the scan phase result and scanner health.
 * Mirrors the preset-metadata derivation in {@link buildPersistableCandidates}
 * so the scan metrics row carries the same preset identity as its candidate rows.
 */
function buildScanMetrics(
  agentId: string,
  phaseResult: TechnicalPhaseResult,
  health: ScannerHealthResult,
  technicalConfig: TechnicalConfig,
  /** Post-filter signal count (after swap identity validation). */
  postFilterSignalCount: number,
): ScanMetricInput {
  const venueFamily = deriveVenueFamily(technicalConfig);
  const styleTier = deriveStyleTier(technicalConfig);
  const presetKey = (technicalConfig as Record<string, unknown>)['preset'] as string ?? 'unknown';
  const presetBehaviorVersion = `ts-${styleTier}-v1`;

  const topConfidence =
    phaseResult.signals.length > 0
      ? Math.max(...phaseResult.signals.map((s) => s.confidence))
      : null;

  const regimeBucket =
    phaseResult.regimeResult?.pass === true ? 'favorable'
    : phaseResult.regimeResult?.pass === false ? 'blocked'
    : 'unavailable';

  return {
    agentId,
    presetKey,
    presetBehaviorVersion,
    venueFamily,
    styleTier,
    scanScope: {
      discovered: phaseResult.candidatesDiscovered,
      symbolsSelected: phaseResult.symbolsSelected,
      eligible: phaseResult.eligibleCount,
      fetched: phaseResult.fetchedCount,
      scored: phaseResult.candidatesScored,
      signals: postFilterSignalCount,
    },
    scannedAt: new Date().toISOString(),
    candidatesDiscovered: phaseResult.candidatesDiscovered,
    candidatesScored: phaseResult.candidatesScored,
    signalsGenerated: postFilterSignalCount,
    scanHealth: health.status,
    topConfidence,
    regimeBucket,
  };
}
